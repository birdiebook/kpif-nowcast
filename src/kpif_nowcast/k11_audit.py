"""K11: re-run K2's preregistered variants with the corrected publication calendar (a correction, not new variants).

`python -m kpif_nowcast.k11_audit diff`  - which K2 feature cells change when known_from follows the calendar
`python -m kpif_nowcast.k11_audit rerun` - all 8 K2 variants on corrected data (Holm over the same 8 as K2)
`python -m kpif_nowcast.k11_audit rerun raw` - the same on the stored (uncorrected) table, as a reproduction check

Results: docs/auto2/k11/k2_rerun_raw.md (and _before.md for the raw run).
"""

from __future__ import annotations

import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "auto2" / "k11"
FROZEN = ["k2_avg_ridge_l", "k2_avg_ens_s", "k2_avg_ridge_s"]
PERIODS = [("2015-02..2026-10 (primary)", "2015-02"), ("2018-02..2026-10 (ML active)", "2018-02"),
           ("2024-01..2026-10 (used, report only)", "2024-01")]


def design(raw: bool) -> pd.DataFrame:
    from kpif_nowcast.data import load_components, load_el_contracts, load_kpif, load_riksbank_forecasts
    from kpif_nowcast.features import load_features
    from kpif_nowcast.j2_el import zone_monthly_spot
    from kpif_nowcast.k2_ml import build_design
    from kpif_nowcast.observations import load as load_obs

    return build_design(load_kpif(), load_components(), load_features(), load_el_contracts(),
                        zone_monthly_spot("SE3"), load_riksbank_forecasts(), load_obs(raw=raw))


def diff() -> pd.DataFrame:
    """Changed feature cells (target months 2015-02..2026-10) between stored and corrected known_from."""
    a, b = design(raw=True), design(raw=False)
    sel = (a.index >= pd.Period("2015-02", "M")) & (a.index <= pd.Period("2026-10", "M"))
    rows = {}
    for c in a.columns:
        x, y = a.loc[sel, c], b.loc[sel, c]
        changed = ~((x == y) | (x.isna() & y.isna()))
        if changed.any():
            rows[c] = {"changed_months": int(changed.sum()),
                       "months": ", ".join(str(p) for p in x.index[changed][:12]) + (" …" if changed.sum() > 12 else "")}
    out = pd.DataFrame(rows).T
    print(out.to_string())
    return out


def rerun(raw: bool = False) -> None:
    from kpif_nowcast.evaluation import log_run
    from kpif_nowcast.j1_hybrid import dm_one_sided
    from kpif_nowcast.j2_el import holm
    from kpif_nowcast.k2_ml import VARIANTS, K2Runner

    warnings.filterwarnings("ignore")
    d = design(raw)
    run = K2Runner(d)
    preds = d[["rb", "j2", "avg"]].rename(columns={"rb": "rb_updated", "avg": "avg_5050"})
    for name in VARIANTS:
        preds[name] = run.series(name)
        print("done", name, flush=True)
    actual = d["actual"]
    refs = ["avg_5050", "rb_updated", "j2"]
    tag = "raw (stored known_from)" if raw else "corrected calendar"
    lines = [f"# K11: K2 variants re-run, {tag} (generated by `python -m kpif_nowcast.k11_audit`)", ""]
    log_rows = []
    for label, start in PERIODS:
        p = preds.loc[pd.Period(start, "M"): pd.Period("2026-10", "M")]
        p = p[actual.reindex(p.index).notna()].dropna()
        err = p.sub(actual.reindex(p.index), axis=0)
        tab = pd.DataFrame({"MAE": err.abs().mean(), "bias": err.mean(), "n": err.count()})
        for ref in refs:
            rawp = {m: dm_one_sided(err[m].to_numpy(), err[ref].to_numpy())[1] for m in VARIANTS}
            h = holm(rawp)
            for m in VARIANTS:
                tab.loc[m, f"diff_{ref}"] = tab.loc[m, "MAE"] - tab.loc[ref, "MAE"]
                tab.loc[m, f"p1_{ref}"] = rawp[m]
                tab.loc[m, f"holm_{ref}"] = h[m]
        for m, row in tab.iterrows():
            log_rows.append({"variant": f"{m} (k11 {'raw' if raw else 'corrected'})", "period": label,
                             "n": int(row["n"]), "MAE": round(row["MAE"], 4),
                             "dm_p_vs_rb_updated": round(row.get("p1_rb_updated", float("nan")), 4)})
        lines.append(f"## {label} (n={len(p)}; DM one-sided, H1: variant lower MAE; Holm over 8 per reference)\n\n"
                     f"{tab.round(4).to_markdown()}\n")
        print(f"\n{label}\n{tab.loc[FROZEN + refs, ['MAE', 'diff_avg_5050', 'p1_avg_5050', 'holm_avg_5050']].round(4)}",
              flush=True)
    path = log_run("k11_k2_rerun_raw" if raw else "k11_k2_rerun", log_rows)
    lines.append(f"Run log: `{path.name}`\n")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / ("k2_rerun_before.md" if raw else "k2_rerun_raw.md")).write_text("\n".join(lines), encoding="utf-8")
    (ROOT / "outputs").mkdir(exist_ok=True)
    preds.join(actual).to_csv(ROOT / "outputs" / ("k11_k2_preds_raw.csv" if raw else "k11_k2_preds.csv"))


if __name__ == "__main__":
    args = sys.argv[1:]
    if args[:1] == ["diff"]:
        diff()
    else:
        rerun(raw=args[1:2] == ["raw"])
