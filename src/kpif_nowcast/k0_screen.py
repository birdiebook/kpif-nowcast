"""K0: screen the price-chain series (catalog_prices) with J3's protocol, then the two preregistered variants.

Protocol and selection rule: docs/auto2/k0/hypotes.md. The screen reuses j3_screen unchanged.
K0-C1: rb_updated + OLS on the three chosen series. K0-C2: the same on the 50/50 average of
rb_updated and J2 V2 (j1_hybrid.build_panel / j1_comb_equal).

Run: python -m kpif_nowcast.k0_screen
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from kpif_nowcast.j3_screen import PRIMARY, combined_h1, run_h1, run_hk, score_table

PERIODS = {"primary 2017-02..2026-10": PRIMARY, "2015-2026": ("2015-01", "2026-10"),
           "2024-2026 (used, report only)": ("2024-01", "2026-10")}


def group(key: str) -> str:
    if key.startswith("ppi_"):
        return "PPI"
    if key.startswith("ki_"):
        return "KI"
    if key.startswith("kpif_"):
        return "KPIF"
    if key.startswith(("gvb_", "swestr")):
        return "rates"
    return "IMF"


def choose(prim: pd.DataFrame, k: int = 3, q: float = 0.10) -> tuple[list[str], str]:
    """Preregistered rule: BH survivors by raw p, filled up with lowest raw p; at most one per source group."""
    order = list(prim[prim["bh_q"] < q].sort_values("p1").index) + list(prim[~(prim["bh_q"] < q)].sort_values("p1").index)
    chosen, groups = [], set()
    for key in order:
        if group(key) in groups:
            continue
        chosen.append(key)
        groups.add(group(key))
        if len(chosen) == k:
            break
    n_surv = int((prim.loc[chosen, "bh_q"] < q).sum())
    tag = "all BH survivors" if n_surv == len(chosen) else f"{n_surv} of {len(chosen)} survived BH"
    return chosen, tag


def fifty_fifty_frame() -> pd.DataFrame:
    from kpif_nowcast.data import load_components, load_el_contracts, load_kpif, load_riksbank_forecasts
    from kpif_nowcast.features import load_features
    from kpif_nowcast.j1_hybrid import build_panel, j1_forecast
    from kpif_nowcast.j2_el import zone_monthly_spot
    from kpif_nowcast.observations import load as load_obs

    panel = build_panel(load_kpif(), load_components(), load_features(), load_el_contracts(),
                        zone_monthly_spot("SE3"), load_riksbank_forecasts(), load_obs())
    return pd.DataFrame({"base": j1_forecast(panel, "j1_comb_equal"), "actual": panel["actual"]})


def one_sided(e_a: np.ndarray, e_b: np.ndarray):
    from kpif_nowcast.evaluation import dm_test

    r = dm_test(e_a, e_b)
    return r, (r.p / 2 if r.mean_diff < 0 else 1 - r.p / 2)


def evaluate(f: pd.DataFrame, pred: pd.Series, start: str, end: str) -> dict:
    sel = (f.index >= pd.Period(start, "M")) & (f.index <= pd.Period(end, "M")) & f["actual"].notna()
    e = (pred[sel] - f["actual"][sel]).to_numpy()
    eb = (f["base"][sel] - f["actual"][sel]).to_numpy()
    r, p1 = one_sided(e, eb)
    return {"MAE": float(np.mean(np.abs(e))), "base_MAE": float(np.mean(np.abs(eb))), "diff": r.mean_diff,
            "p1": p1, "n": r.n, "n_active": int((pred[sel] != f["base"][sel]).sum())}


def main() -> None:
    import warnings
    from pathlib import Path

    from kpif_nowcast import catalog_prices
    from kpif_nowcast import observations as obs
    from kpif_nowcast.catalog import by_key
    from kpif_nowcast.data import load_kpif, load_riksbank_forecasts
    from kpif_nowcast.evaluation import log_run
    from kpif_nowcast.j2_el import holm

    warnings.filterwarnings("ignore")
    kpif, rb_fc, table = load_kpif(), load_riksbank_forecasts(), obs.load()
    specs = by_key()
    keys = catalog_prices.keys()
    keys_units = [(k, specs[k].unit) for k in keys]
    revised = {k: specs[k].revised for k in keys}

    lines = ["# K0 screening, raw tables (generated by `python -m kpif_nowcast.k0_screen`)", ""]
    log_rows = []
    f1, p1, xs = run_h1(kpif, rb_fc, table, keys_units)
    tabs = {}
    for label, (s, e) in list(PERIODS.items())[:2]:
        tabs[f"h=1 {label}"] = score_table(f1, p1, s, e, 1, revised)
    for h in (3, 12):
        fh, ph = run_hk(kpif, rb_fc, table, keys_units, h)
        tabs[f"h={h} targets 2017-02..2026-10"] = score_table(fh, ph, *PRIMARY, h, revised, target_col="target")
    for label, t in tabs.items():
        base = "rb_updated" if label.startswith("h=1") else "Riksbank"
        lines.append(f"## {label} (base {base} MAE {t.attrs['base_mae']:.3f}, n={t.attrs['n']})\n\n"
                     f"{t.astype({'MAE': float, 'diff': float, 'p1': float}).round(3).to_markdown()}\n")
        for k, row in t.iterrows():
            log_rows.append({"variant": f"k0s_{k}", "period": label, "n": int(row["n"]),
                             "MAE": round(float(row["MAE"]), 4), "dm_p_vs_rb_updated": round(float(row["p1"]), 4)})
        print(label, t.head(6)[["MAE", "diff", "p1", "bh_q", "revised"]], sep="\n")

    chosen, tag = choose(tabs["h=1 primary 2017-02..2026-10"])
    lines.append(f"## Chosen for the variants ({tag}): {', '.join(chosen)}\n")
    f2 = fifty_fifty_frame()
    variants = {"k0_c1": (f1, combined_h1(f1, xs, chosen)), "k0_c2": (f2, combined_h1(f2, xs, chosen))}
    res = {v: {lab: evaluate(f, pred, *per) for lab, per in PERIODS.items()} for v, (f, pred) in variants.items()}
    holm_p = holm({v: res[v]["primary 2017-02..2026-10"]["p1"] for v in res})
    rows = []
    for v in res:
        for lab, r in res[v].items():
            rows.append({"variant": v, "base": "rb_updated" if v == "k0_c1" else "50/50 rb_updated+J2 V2",
                         "period": lab, **r, "holm_p": holm_p[v] if lab.startswith("primary") else np.nan})
            log_rows.append({"variant": v, "period": lab, "n": r["n"], "MAE": round(r["MAE"], 4),
                             "dm_p_vs_rb_updated": round(r["p1"], 4)})  # one-sided, vs the variant's own base
    vt = pd.DataFrame(rows)
    lines.append(vt.round(4).to_markdown(index=False) + "\n")
    print(vt.round(4).to_string())
    path = log_run("k0_screen", log_rows)
    lines.append(f"Run log: `{path.name}`\n")
    root = Path(__file__).resolve().parents[2]
    (root / "docs" / "auto2" / "k0" / "results_raw.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
